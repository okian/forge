package racetest

import (
	"fmt"
	"go/format"
	"strings"
)

// Declared is one declaration the matrix puts a layer through.
type Declared struct {
	// Name is the type the declaration introduces, and Layer the concurrent
	// layer it is here to exercise.
	Name  string
	Layer string

	// Stack is every marker in the declaration, outermost first, and Subject
	// the type at the bottom of it.
	Stack   []string
	Subject string

	// Directives are the lines written above it, each already spelled the way
	// an author writes one.
	Directives []string
}

// Spec writes the declarations the matrix generates from.
//
// Written rather than kept by hand, and that is the whole of what makes the
// matrix grow on its own: the set of declarations is the set of concurrent
// layers, so a layer added to the catalog is a declaration here, a package
// generated for it, and a stress test run against it — with nothing for anybody
// to remember. A file somebody had to edit would be the thing forgotten on the
// week the layer landed.
//
// It carries the marker package's build tag, so exactly one of it and the
// generated declaration is ever in scope. That is the arrangement a stack needs
// wherever it is written: the underlying type is forge's rather than an
// author's, so forge owns the declaration and this owns the description of it.
func Spec(pkg, marker string, held []Declared) ([]byte, error) {
	if pkg == "" || marker == "" {
		return nil, fmt.Errorf(
			"a spec file needs a package and the import path its markers come from, and was "+
				"asked for %q and %q", pkg, marker)
	}
	if len(held) == 0 {
		return nil, fmt.Errorf(
			"a spec file with no declarations in it is a file nothing generates from, and %s "+
				"was given none", pkg)
	}

	w := &strings.Builder{}

	w.WriteString("//go:build forgespec\n\n")
	w.WriteString("// Code generated by forge's race harness. DO NOT EDIT.\n")
	w.WriteString("//\n")
	w.WriteString("// This is the spec side of the declarations the matrix runs: one per layer\n")
	w.WriteString("// that makes a stack safe to share, written from the catalog rather than by\n")
	w.WriteString("// hand, so that a layer added to the catalog cannot arrive without one.\n")
	w.WriteString("//\n")
	w.WriteString("// The stack under each of them is the same on purpose. A bounded container\n")
	w.WriteString("// of elements that carry a codec is the arrangement with the most surface\n")
	w.WriteString("// for a concurrent layer to get wrong — a walk, a count, a copy and a\n")
	w.WriteString("// document — so it is what every one of them is put through, and the only\n")
	w.WriteString("// thing that differs between the tests is the layer being tested.\n")
	w.WriteString("package " + pkg + "\n\n")
	w.WriteString("import \"" + marker + "\"\n")

	for _, one := range held {
		if err := declaring(w, one, marker); err != nil {
			return nil, err
		}
	}

	out, err := format.Source([]byte(w.String()))
	if err != nil {
		return nil, fmt.Errorf("what was written for %s is not valid Go: %w", pkg, err)
	}
	return out, nil
}

// declaring writes one declaration and the lines above it.
func declaring(w *strings.Builder, of Declared, marker string) error {
	if of.Name == "" || of.Layer == "" || of.Subject == "" || len(of.Stack) == 0 {
		return fmt.Errorf(
			"a declaration needs a name, the layer it is for, a subject and a stack, and was "+
				"asked for %q, %q, %q and %v", of.Name, of.Layer, of.Subject, of.Stack)
	}

	w.WriteString("\n// " + of.Name + " is what the " + of.Layer + " layer is put through.\n")
	for _, one := range of.Directives {
		w.WriteString("//\n//" + one + "\n")
	}

	w.WriteString("type " + of.Name + " " + spelled(of, marker) + "\n")
	return nil
}

// spelled writes the stack as an author writes one: the markers nested
// outermost first, with the subject at the bottom.
func spelled(of Declared, marker string) string {
	held := strings.Builder{}

	name := marker[strings.LastIndex(marker, "/")+1:]
	for _, one := range of.Stack {
		held.WriteString(name + "." + one + "[")
	}

	held.WriteString(of.Subject)
	held.WriteString(strings.Repeat("]", len(of.Stack)))

	return held.String()
}
