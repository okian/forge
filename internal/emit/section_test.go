// whole parses a complete file, as a layer's template really is, and hands over
// every declaration and every comment in it.
func whole(t *testing.T, source string) emit.Section {
	t.Helper()

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "tmpl.go", source, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}

	return emit.Section{Decls: file.Decls, Comments: file.Comments, Fset: fset}
}

// A layer's declarations come out of an ordinary Go file, and an ordinary Go
// file opens with a comment far more often than not. Every one of these is a
// template somebody would write.
func TestSectionsComeFromOrdinaryFiles(t *testing.T) {
	const body = "\npackage tmpl\n\n// Len reports how many there are.\nfunc Len() int { return 0 }\n"

	cases := map[string]string{
		"nothing above the clause": body,
		"a package comment":        "// Package tmpl is the collection template." + body,
		"a licence":                "// Copyright 2026 the authors.\n// SPDX-License-Identifier: MIT\n" + body,
		"a build constraint":       "//go:build tmpl\n" + body,
		"a linter directive":       "//nolint:all\n" + body,
		"a generated marker":       "// Code generated by something. DO NOT EDIT.\n" + body,
		"a blank line first":       "\n// Package tmpl is the collection template." + body,
	}

	for name, source := range cases {
		t.Run(name, func(t *testing.T) {
			out, err := emit.File{
				Package:  "model",
				Sections: []emit.Section{whole(t, source)},
			}.Render()
			if err != nil {
				t.Fatalf("render: %v", err)
			}

			rendered := string(out)
			if !strings.Contains(rendered, "// Len reports how many there are.\nfunc Len() int") {
				t.Errorf("the declaration lost its own comment:\n%s", rendered)
			}
			// Nothing above the template's package clause is about the
			// declarations, and none of it belongs in the output. The check
			// starts below forge's own header, which says some of the same
			// words on purpose.
			_, body, _ := strings.Cut(rendered, "package model")
			for _, unwanted := range []string{"Package tmpl", "Copyright", "go:build tmpl", "nolint", "Code generated by something"} {
				if strings.Contains(body, unwanted) {
					t.Errorf("%q leaked out of the template:\n%s", unwanted, rendered)
				}
			}
		})
	}
}

// A layer keeps some of its template's declarations and drops the rest. The
// comments of the ones it dropped would otherwise be printed beside the ones it
// kept, saying nothing about them.
func TestCommentsOfDroppedDeclarationsDoNotFollow(t *testing.T) {
	const source = `package tmpl

// helper is internal to the template and is never emitted.
func helper() {}

// Len reports how many there are.
func Len() int {
	// count them
	return 0
}

// trailing is internal too.
func trailing() {}
`

	all := whole(t, source)

	// Only the middle declaration is kept, which is what a rewrite does.
	kept := emit.Section{Decls: []ast.Decl{all.Decls[1]}, Comments: all.Comments, Fset: all.Fset}

	out, err := emit.File{Package: "model", Sections: []emit.Section{kept}}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	rendered := string(out)
	for _, want := range []string{"// Len reports how many there are.\nfunc Len() int", "// count them"} {
		if !strings.Contains(rendered, want) {
			t.Errorf("%q did not survive:\n%s", want, rendered)
		}
	}
	for _, unwanted := range []string{"helper", "trailing"} {
		if strings.Contains(rendered, unwanted) {
			t.Errorf("%q came along with a declaration nobody kept:\n%s", unwanted, rendered)
		}
	}
}

// A rewrite keeps what it read and builds what it did not, and a comment kept
// from one file above a declaration built for another is a comment that will be
// printed after the thing it documents. Nothing about the file's comment list
// changes that, so it is refused rather than written.
func TestAParsedCommentOnABuiltDeclarationIsRefused(t *testing.T) {
	parsed := whole(t, "package tmpl\n\n// Len reports how many there are.\nfunc Len() int { return 0 }\n")

	built := &ast.GenDecl{
		Doc: parsed.Comments[0],
		Tok: token.TYPE,
		Specs: []ast.Spec{&ast.TypeSpec{
			Name: ast.NewIdent("Persons"),
			Type: &ast.ArrayType{Elt: ast.NewIdent("Person")},
		}},
	}

	_, err := emit.File{
		Package:  "model",
		Decl:     "Persons",
		Sections: []emit.Section{{Decls: []ast.Decl{built}, Comments: parsed.Comments, Fset: parsed.Fset}},
	}.Render()

	if err == nil {
		t.Fatal("a comment positioned after what it documents was written")
	}
	for _, want := range []string{"FRG4002", "positioned after it", "Len reports"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error does not mention %q:\n%v", want, err)
		}
	}
}

// A declaration and its comment that were both built carry no positions at all,
// which is not a disagreement: the printer takes the comment from the
// declaration and writes it above.
func TestABuiltDeclarationKeepsItsBuiltComment(t *testing.T) {
	out, err := emit.File{
		Package: "model",
		Sections: []emit.Section{{Decls: []ast.Decl{&ast.GenDecl{
			Doc: &ast.CommentGroup{List: []*ast.Comment{{Text: "// Persons holds people."}}},
			Tok: token.TYPE,
			Specs: []ast.Spec{&ast.TypeSpec{
				Name: ast.NewIdent("Persons"),
				Type: &ast.ArrayType{Elt: ast.NewIdent("Person")},
			}},
		}}}},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	if want := "// Persons holds people.\ntype Persons []Person"; !strings.Contains(string(out), want) {
		t.Errorf("the comment and the declaration came apart:\n%s", out)
	}
}

// Anything the parser could not make sense of prints as the words "BadDecl",
// which is not Go. It is caught where every other thing that is not Go is
// caught, with the source it could not parse quoted back.
func TestADeclarationTheParserGaveUpOn(t *testing.T) {
	parsed := whole(t, "package tmpl\n\n// Len reports how many there are.\nfunc Len() int { return 0 }\n")

	_, err := emit.File{
		Package: "model",
		Decl:    "Persons",
		Sections: []emit.Section{{
			Decls:    []ast.Decl{&ast.BadDecl{From: parsed.Decls[0].Pos(), To: parsed.Decls[0].End()}},
			Comments: parsed.Comments,
			Fset:     parsed.Fset,
		}},
	}.Render()

	if err == nil {
		t.Fatal("a declaration the parser gave up on rendered without complaint")
	}
	if !strings.Contains(err.Error(), "FRG4001") {
		t.Errorf("error %q is not a diagnostic about output that will not parse", err)
	}
}

// A layer emits a type, then its constructor, then its methods, which is
// almost never the order its template declares them in. The printer places a
// declaration where it is told and a comment where its position says, and an
// order that disagrees with the source would leave every comment behind.
func TestDeclarationsMayBeReordered(t *testing.T) {
	all := whole(t, `package tmpl

// Alpha is declared first.
type Alpha struct{}

// Beta is declared second.
type Beta struct{}

// Gamma is declared third.
type Gamma struct{}
`)

	out, err := emit.File{
		Package: "model",
		Sections: []emit.Section{{
			Decls:    []ast.Decl{all.Decls[2], all.Decls[0], all.Decls[1]},
			Comments: all.Comments,
			Fset:     all.Fset,
		}},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	rendered := string(out)
	for _, want := range []string{
		"// Gamma is declared third.\ntype Gamma struct{}",
		"// Alpha is declared first.\ntype Alpha struct{}",
		"// Beta is declared second.\ntype Beta struct{}",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("%q is not written as one block:\n%s", want, rendered)
		}
	}
}

// A template is a package rather than a file, and an offset is counted within a
// file, so two files' positions do not order against each other at all.
func TestDeclarationsMayComeFromTwoFilesOfOnePackage(t *testing.T) {
	fset := token.NewFileSet()

	read := func(name, source string) *ast.File {
		t.Helper()

		file, err := parser.ParseFile(fset, name, source, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			t.Fatalf("parse %s: %v", name, err)
		}
		return file
	}

	first := read("a.go", "package tmpl\n\n// Alpha lives in a.go, further along than Beta does in its own file.\ntype Alpha struct{}\n")
	second := read("b.go", "package tmpl\n\n// Beta lives in b.go.\ntype Beta struct{}\n")

	out, err := emit.File{
		Package: "model",
		Sections: []emit.Section{{
			Decls:    []ast.Decl{first.Decls[0], second.Decls[0]},
			Comments: slices.Concat(first.Comments, second.Comments),
			Fset:     fset,
		}},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	rendered := string(out)
	for _, want := range []string{
		"// Alpha lives in a.go, further along than Beta does in its own file.\ntype Alpha struct{}",
		"// Beta lives in b.go.\ntype Beta struct{}",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("%q is not written as one block:\n%s", want, rendered)
		}
	}
}

// Two files added to one file set under one name are still two files, their
// offsets are counted separately, and a name cannot tell them apart. A
// rewriting engine parses fragments and calls them all the same thing, so this
// is the ordinary case rather than the exotic one.
func TestTwoFilesUnderOneNameAreStillTwoFiles(t *testing.T) {
	fset := token.NewFileSet()

	read := func(source string) *ast.File {
		t.Helper()

		file, err := parser.ParseFile(fset, "layer.go", source, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			t.Fatalf("parse: %v", err)
		}
		return file
	}

	// The first fragment's declaration sits further into its file than the
	// second's does into its own, so their offsets run backwards.
	first := read("package tmpl\n\n// Alpha is a long way into its own file, further than Beta is into its.\ntype Alpha struct{}\n")
	second := read("package tmpl\n\n// Beta is near the top.\ntype Beta struct{}\n")

	out, err := emit.File{
		Package: "model",
		Sections: []emit.Section{{
			Decls:    []ast.Decl{first.Decls[0], second.Decls[0]},
			Comments: slices.Concat(first.Comments, second.Comments),
			Fset:     fset,
		}},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	rendered := string(out)
	for _, want := range []string{
		"// Alpha is a long way into its own file, further than Beta is into its.\ntype Alpha struct{}",
		"// Beta is near the top.\ntype Beta struct{}",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("%q is not written as one block:\n%s", want, rendered)
		}
	}
}

// A template imports what it needs, and the parser puts that declaration in
// with the rest. Written out it would appear a second time below the block the
// file already wrote, and the file would not compile.
func TestATemplatesImportsAreNotWrittenTwice(t *testing.T) {
	template := whole(t, `package tmpl

import (
	"slices"
	"iter"
)

// All walks them.
func All(items []int) iter.Seq[int] { return slices.Values(items) }
`)

	out, err := emit.File{
		Package:  "model",
		Imports:  []emit.Import{{Path: "iter", Name: "iter"}, {Path: "slices", Name: "slices"}},
		Sections: []emit.Section{template},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	rendered := string(out)
	if got := strings.Count(rendered, "\"iter\""); got != 1 {
		t.Errorf("iter is imported %d times:\n%s", got, rendered)
	}
	if got := strings.Count(rendered, "import"); got != 1 {
		t.Errorf("the file has %d import blocks:\n%s", got, rendered)
	}
	if !strings.Contains(rendered, "// All walks them.\nfunc All(") {
		t.Errorf("the declaration did not survive:\n%s", rendered)
	}
}

// A section holding nothing but its template's furniture writes nothing, which
// is what lets the stage above it leave the layer out.
func TestASectionOfNothingButImportsIsEmpty(t *testing.T) {
	template := whole(t, "package tmpl\n\nimport \"iter\"\n")

	if !template.Empty() {
		t.Error("a section holding only an import reports itself as having something to write")
	}
}

// A nil pointer of a declaration type is a value the language will not tell you
// is empty. Asking a section whether it would write anything happens before
// there is anywhere to report to — the stage that merges asks it — so it has to
// answer rather than raise.
func TestATypedNilIsAValueRatherThanAGap(t *testing.T) {
	var (
		noType *ast.GenDecl
		noFunc *ast.FuncDecl
	)

	for name, missing := range map[string]ast.Decl{"a type": noType, "a function": noFunc} {
		t.Run(name, func(t *testing.T) {
			section := emit.Section{Decls: []ast.Decl{missing}}

			if section.Empty() {
				t.Error("a section holding a declaration that is nothing reports itself empty")
			}

			// And writing it is a diagnostic rather than a crash.
			_, err := emit.File{Package: "model", Decl: "Persons", Sections: []emit.Section{section}}.Render()
			if err == nil {
				t.Fatal("a declaration that is nothing rendered without complaint")
			}
			if !strings.Contains(err.Error(), "FRG4002") {
				t.Errorf("error %q is not a diagnostic about a malformed declaration", err)
			}
		})
	}
}

// A rewrite keeps some declarations and builds others, and a file with any
// comment list at all has every declaration's own doc comment turned off. A
// built declaration beside a parsed one would then lose the comment it carries.
func TestABuiltDeclarationBesideAParsedOneKeepsItsComment(t *testing.T) {
	parsed := whole(t, "package tmpl\n\n// Len reports how many there are.\nfunc Len() int {\n\t// count them\n\treturn 0\n}\n")

	built := &ast.GenDecl{
		Doc: &ast.CommentGroup{List: []*ast.Comment{{Text: "// Persons holds people."}}},
		Tok: token.TYPE,
		Specs: []ast.Spec{&ast.TypeSpec{
			Name: ast.NewIdent("Persons"),
			Type: &ast.ArrayType{Elt: ast.NewIdent("Person")},
		}},
	}

	for name, decls := range map[string][]ast.Decl{
		"built first":  {built, parsed.Decls[0]},
		"parsed first": {parsed.Decls[0], built},
	} {
		t.Run(name, func(t *testing.T) {
			out, err := emit.File{
				Package:  "model",
				Sections: []emit.Section{{Decls: decls, Comments: parsed.Comments, Fset: parsed.Fset}},
			}.Render()
			if err != nil {
				t.Fatalf("render: %v", err)
			}

			rendered := string(out)
			for _, want := range []string{
				"// Persons holds people.\ntype Persons []Person",
				"// Len reports how many there are.\nfunc Len() int",
				"// count them",
			} {
				if !strings.Contains(rendered, want) {
					t.Errorf("%q is missing or came apart:\n%s", want, rendered)
				}
			}
		})
	}
}

// A tree with a hole in it raises when it is asked where it is, and asking is
// what deciding where a comment goes consists of. Every one of those questions
// is asked under the same recover as the printing.
func TestTreesWithHolesAreReportedRatherThanPanicking(t *testing.T) {
	parsed := whole(t, "package tmpl\n\n// Len reports how many there are.\nfunc Len() int { return 0 }\n")

	// A type declared as nothing has no end for a comment to be compared
	// against, and comparing is what deciding where a comment goes consists of.
	_, err := emit.File{
		Package: "model",
		Decl:    "Persons",
		Sections: []emit.Section{{
			Decls: []ast.Decl{&ast.GenDecl{
				Tok:   token.TYPE,
				Specs: []ast.Spec{&ast.TypeSpec{Name: ast.NewIdent("Persons")}},
			}},
			Comments: parsed.Comments,
			Fset:     parsed.Fset,
		}},
	}.Render()

	if err == nil {
		t.Fatal("a tree with a hole in it rendered without complaint")
	}
	if !strings.Contains(err.Error(), "FRG4002") {
		t.Errorf("error %q is not a diagnostic about a malformed declaration", err)
	}
}

// A comment group holding no comments is nowhere rather than malformed. It says
// nothing, so writing nothing for it is the whole of what it deserves.
func TestAnEmptyCommentGroupIsIgnored(t *testing.T) {
	out, err := emit.File{
		Package: "model",
		Sections: []emit.Section{{
			Decls: []ast.Decl{&ast.GenDecl{
				Doc:   &ast.CommentGroup{},
				Tok:   token.TYPE,
				Specs: []ast.Spec{&ast.TypeSpec{Name: ast.NewIdent("Persons"), Type: ast.NewIdent("int")}},
			}},
		}},
	}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	if want := "type Persons int"; !strings.Contains(string(out), want) {
		t.Errorf("rendered:\n%s", out)
	}
}

// A doc comment sits directly above what it documents, with nothing between.
