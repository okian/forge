package emit_test

import (
	"strings"
	"testing"

	"github.com/okian/forge/internal/emit"
)

// What a file records has to be readable back out of it, or a staleness check
// has to regenerate the file to find out whether it needed to.
func TestHeaderRoundTrips(t *testing.T) {
	want := emit.Header{Forge: "v0.1.0", Markers: "v0.2.1", Inputs: "0123456789abcdef"}

	out, err := emit.File{Package: "model", Build: "!forgespec", Header: want}.Render()
	if err != nil {
		t.Fatalf("render: %v", err)
	}

	got, ok := emit.ReadHeader(out)
	if !ok {
		t.Fatalf("a file forge wrote does not read as one:\n%s", out)
	}
	if got != want {
		t.Errorf("read back %+v, want %+v", got, want)
	}
}

// A file forge wrote stays one after something else has been at it. Reading it
// as somebody else's would leave it both unchecked for staleness and protected
// from being refreshed, which is the worst of both answers.
func TestReadHeaderSurvivesWhatToolsDoToFiles(t *testing.T) {
	cases := map[string]string{
		"a leading blank line": "\n" + emit.Generated + "\n//\n// forge v0.1.0\n\npackage model\n",
		"a licence block above": "// Copyright the authors.\n// SPDX-License-Identifier: MIT\n\n" +
			emit.Generated + "\n//\n// forge v0.1.0\n\npackage model\n",
		"windows line endings": emit.Generated + "\r\n//\r\n// forge v0.1.0\r\n\r\npackage model\r\n",
		"a byte order mark":    "\ufeff" + emit.Generated + "\n//\n// forge v0.1.0\n\npackage model\n",
		"a constraint between": emit.Generated + "\n\n//go:build !forgespec\n\n" +
			"// forge v0.1.0\n\npackage model\n",
	}

	for name, source := range cases {
		t.Run(name, func(t *testing.T) {
			got, ok := emit.ReadHeader([]byte(source))
			if !ok {
				t.Fatalf("a file forge wrote does not read as one:\n%s", source)
			}
			if got.Forge != "v0.1.0" {
				t.Errorf("forge = %q, want v0.1.0", got.Forge)
			}
		})
	}
}

// A value may hold spaces, since a version string built from a commit does.
func TestReadHeaderKeepsAValueWhole(t *testing.T) {
	source := emit.Generated + "\n//\n// forge v0.1.0 (devel abc1234)\n\npackage model\n"

	got, _ := emit.ReadHeader([]byte(source))
	if want := "v0.1.0 (devel abc1234)"; got.Forge != want {
		t.Errorf("forge = %q, want %q", got.Forge, want)
	}
}

// A file nobody generated is not one to be checked for staleness, overwritten,
// or otherwise treated as forge's.
func TestReadHeaderOfSomethingElse(t *testing.T) {
	cases := map[string]string{
		"hand written":    "package model\n\ntype Persons []Person\n",
		"another tool":    "// Code generated by stringer. DO NOT EDIT.\n\npackage model\n",
		"nothing at all":  "",
		"a bare comment":  "// something a person wrote\n\npackage model\n",
		"the words later": "package model\n\n" + emit.Generated + "\n",
	}

	for name, source := range cases {
		t.Run(name, func(t *testing.T) {
			if _, ok := emit.ReadHeader([]byte(source)); ok {
				t.Errorf("read as forge's own:\n%s", source)
			}
		})
	}
}

// The fields are optional. A file that says it is generated and records nothing
// is still forge's; it is only expensive to check.
func TestReadHeaderWithoutFields(t *testing.T) {
	got, ok := emit.ReadHeader([]byte(emit.Generated + "\n\npackage model\n"))

	if !ok {
		t.Fatal("a file that says it is generated was not read as one")
	}
	if !got.IsZero() {
		t.Errorf("read %+v out of a file that records nothing", got)
	}
}

// Reading stops where the comment block does, so nothing that happens to look
// like a field further down the file is mistaken for one.
func TestReadHeaderStopsAtTheCode(t *testing.T) {
	source := emit.Generated + "\n" +
		"//\n" +
		"// forge v0.1.0\n" +
		"\n" +
		"package model\n" +
		"\n" +
		"// inputs deadbeefdeadbeef\n" +
		"type Persons []Person\n"

	got, ok := emit.ReadHeader([]byte(source))
	if !ok {
		t.Fatal("a file forge wrote does not read as one")
	}
	if got.Forge != "v0.1.0" {
		t.Errorf("forge = %q, want v0.1.0", got.Forge)
	}
	if got.Inputs != "" {
		t.Errorf("inputs = %q, read from below the header", got.Inputs)
	}
}

// A comment that is not a field is passed over rather than read as a broken
// one, since a header may grow prose.
func TestReadHeaderIgnoresWhatItDoesNotKnow(t *testing.T) {
	source := emit.Generated + "\n" +
		"//\n" +
		"// this file is generated; edit the declaration instead\n" +
		// A word on its own is not a field, and reading it as one would record
		// a name with no value under a name nobody wrote.
		"// forge\n" +
		"// forge v0.1.0\n" +
		"//\n" +
		"\npackage model\n"

	got, ok := emit.ReadHeader([]byte(source))
	if !ok {
		t.Fatal("a file forge wrote does not read as one")
	}
	if got.Forge != "v0.1.0" {
		t.Errorf("forge = %q, want v0.1.0", got.Forge)
	}
}

// The marker line is what the go command recognises, so it is written exactly.
func TestGeneratedLineMatchesTheConvention(t *testing.T) {
	if !strings.HasPrefix(emit.Generated, "// Code generated ") {
		t.Errorf("%q does not open the way the convention requires", emit.Generated)
	}
	if !strings.HasSuffix(emit.Generated, " DO NOT EDIT.") {
		t.Errorf("%q does not close the way the convention requires", emit.Generated)
	}
}
