package emit

import (
	"bufio"
	"bytes"
	"fmt"
	"strings"
)

// Generated is the line that marks a file as generated.
//
// The wording is not forge's to choose. The go command recognises a generated
// file by a line matching this shape, and tools from vet to code review lean on
// it, so it is written exactly and it is written first.
const Generated = "// Code generated by forge. DO NOT EDIT."

// Header field names, which are part of the file format rather than prose: the
// stage that checks a file for staleness reads them back.
const (
	fieldForge     = "forge"
	fieldMarkers   = "markers"
	fieldToolchain = "go"
	fieldInputs    = "inputs"
)

// headerPrefix opens every header field line.
const headerPrefix = "// "

// byteOrderMark is what some editors put at the start of a file. It is
// neither a comment nor code, and a file forge wrote does not stop being one
// because a tool added it.
var byteOrderMark = []byte{0xEF, 0xBB, 0xBF}

// Header is what a generated file records about how it was produced.
//
// Two versions rather than one, because they can disagree: the markers a
// declaration is written against come from a module the author depends on,
// while the layers that read them are compiled into the tool. A file generated
// when those agreed and read when they do not is a different problem from a
// file that is merely out of date, and a reader cannot tell them apart from the
// output alone.
type Header struct {
	// Forge is the version of the tool that wrote the file.
	Forge string

	// Markers is the version of the marker module the declaration was written
	// against.
	Markers string

	// Toolchain is the Go that formatted the file.
	//
	// Recorded because it is one of the fingerprint's inputs — the same
	// declarations printed by a later gofmt are different bytes — and a
	// fingerprint that has moved says only that something did. With all three
	// written down, a reader that finds a mismatch can recompute against what
	// the file says and tell "the tooling moved under it" from "the declaration
	// changed", which want different words and different urgency.
	Toolchain string

	// Inputs is the fingerprint of everything the file was made from, which is
	// what makes a staleness check a comparison rather than a regeneration.
	Inputs string
}

// IsZero reports whether the header records nothing.
func (h Header) IsZero() bool { return h == Header{} }

// render writes the header as the comment block that opens a generated file.
//
// A value carrying a line break would write lines of its own into the file,
// which is how a version string from somewhere else becomes a field nobody
// recorded, so one is refused rather than escaped: there is no version, path or
// fingerprint that legitimately holds one.
func (h Header) render(b *strings.Builder) error {
	b.WriteString(Generated)
	b.WriteByte('\n')

	if h.IsZero() {
		return nil
	}

	b.WriteString("//\n")
	for _, field := range []struct{ name, value string }{
		{fieldForge, h.Forge},
		{fieldMarkers, h.Markers},
		{fieldToolchain, h.Toolchain},
		{fieldInputs, h.Inputs},
	} {
		value := strings.TrimSpace(field.value)
		if value == "" {
			continue
		}
		if strings.ContainsAny(value, "\r\n") {
			return fmt.Errorf("header field %s holds a line break: %q", field.name, field.value)
		}

		b.WriteString(headerPrefix)
		b.WriteString(field.name)
		b.WriteByte(' ')
		b.WriteString(value)
		b.WriteByte('\n')
	}

	return nil
}

// ReadHeader recovers the header from a generated file, and reports whether the
// file is one forge wrote at all.
//
// It reads the comment block and stops at the first line that is not one, so a
// file whose header has been edited into something else is reported as not
// forge's rather than parsed into a wrong answer. A file that says it is
// generated and records nothing is still forge's: the fields are optional, and
// an empty digest means only that staleness cannot be decided cheaply.
func ReadHeader(src []byte) (Header, bool) {
	// A byte order mark is not a comment and is not code, and an editor that
	// adds one would otherwise turn a generated file into one forge disowns.
	src = bytes.TrimPrefix(src, byteOrderMark)

	var (
		out     Header
		scanner = bufio.NewScanner(bytes.NewReader(src))
		found   bool
	)

	for scanner.Scan() {
		line := strings.TrimRight(scanner.Text(), " \t")

		switch {
		case line == Generated:
			found = true

		case line == "":
			// A blank line above the marker separates it from a licence block
			// or is simply there; a blank line below it separates the header
			// from the code. Neither ends the search, because the go command's
			// own rule is that the marker appears anywhere before the package
			// clause, and a file forge disowns is one it will neither refresh
			// nor refuse to overwrite.
			continue

		case !strings.HasPrefix(line, "//"):
			// The comment block is over, and with it anything a header could
			// be hiding in.
			return out, found

		case found:
			name, value, ok := field(line)
			if !ok {
				continue
			}
			switch name {
			case fieldForge:
				out.Forge = value
			case fieldMarkers:
				out.Markers = value
			case fieldToolchain:
				out.Toolchain = value
			case fieldInputs:
				out.Inputs = value
			}
		}
	}

	return out, found
}

// field splits a header line into its name and value.
//
// The space after the comment marker is not required, and neither is exactly
// one of it: a header is written by forge and read after anything at all may
// have reformatted it, so what is read back is whatever a human would read.
// Nothing else in a generated file is shaped like a field — a directive has no
// space before its colon and a constraint's name holds one — so a lenient split
// costs nothing.
//
// It is only reached for a line already known to be a comment, so it takes the
// marker off without asking whether it was there.
func field(line string) (string, string, bool) {
	name, value, ok := strings.Cut(strings.TrimSpace(strings.TrimPrefix(line, "//")), " ")
	if !ok {
		return "", "", false
	}

	return name, strings.TrimSpace(value), true
}
