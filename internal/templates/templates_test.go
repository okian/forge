package templates_test

import (
	_ "embed"
	"go/token"
	"strings"
	"testing"

	"github.com/okian/forge/internal/emit"
	"github.com/okian/forge/internal/goldentest"
	"github.com/okian/forge/internal/templates"
)

// toy is the template these tests specialise: a container with methods, a
// helper type, a package-level function and two imports.
//
// Embedded rather than written into a string, so that it is a Go file the
// ordinary build compiles and the ordinary vet reads. A template that only
// existed as a quoted string would be exactly the arrangement this package
// exists instead of.
//
//go:embed testdata/tmpl/tmpl.go
var toy []byte

// where stands in for the declaration that asked, which is what a fault in a
// template is reported against.
var where = token.Position{Filename: "model/spec.go", Line: 8, Column: 6}

// persons specialises the toy template the way a declaration would.
func persons(t *testing.T) templates.Result {
	t.Helper()

	out, diags := templates.Apply(
		templates.Template{Name: "toy", Source: toy},
		templates.Rewrite{
			Param: "T", Subject: "Person",
			Container: "Collection", Declared: "Persons",
			Prefix: "persons",
		}, where)

	if !diags.Empty() {
		t.Fatalf("the template was refused:\n%s", diags.Render())
	}
	return out
}

// rendered returns the specialised template as the source it would be written
// as.
func rendered(t *testing.T, out templates.Result) string {
	t.Helper()

	text, err := emit.Section{Decls: out.Decls, Comments: out.Comments, Fset: out.Fset}.Render()
	if err != nil {
		t.Fatalf("rendering: %v", err)
	}
	return text
}

// A template is Go before it is rewritten and Go after, and the only way to
// know the second is to compile it. The gate is the same one every layer's
// output goes through.
func TestATemplateBecomesAPackageThatCompiles(t *testing.T) {
	out := persons(t)

	var imports strings.Builder
	if len(out.Imports) > 0 {
		imports.WriteString("import (\n")
		for _, one := range out.Imports {
			imports.WriteString("\t" + one.String() + "\n")
		}
		imports.WriteString(")\n\n")
	}

	generated := "// Code generated by forge. DO NOT EDIT.\n\npackage model\n\n" +
		imports.String() + rendered(t, out) + "\n"

	goldentest.Check(t, goldentest.Package{
		Path: "model",
		Files: []goldentest.Source{
			{
				Name: "person.go",
				Content: []byte("package model\n\n" +
					"type Person struct {\n\tName string\n\tAge  int\n}\n"),
			},
			{Name: "forge.gen.go", Content: []byte(generated), Generated: true},
		},
	})
}

// The element is what the declaration named, everywhere the template mentioned
// its parameter.
func TestTheElementBecomesTheSubject(t *testing.T) {
	text := rendered(t, persons(t))

	if strings.Contains(text, "[T]") || strings.Contains(text, "T any") {
		t.Errorf("the type parameter survived the rewrite:\n%s", text)
	}
	for _, want := range []string{"iter.Seq[Person]", "more ...Person"} {
		if !strings.Contains(text, want) {
			t.Errorf("the subject is not written as %q:\n%s", want, text)
		}
	}
}

// The container is what the author called it, in its declaration, in every
// receiver, and in the one method that returns it — which is where a rewrite
// most easily leaves a type nobody declared.
func TestTheContainerBecomesTheDeclaredName(t *testing.T) {
	text := rendered(t, persons(t))

	if strings.Contains(text, "Collection") {
		t.Errorf("the template's own name survived the rewrite:\n%s", text)
	}
	if strings.Contains(text, "Persons[") {
		t.Errorf("the declared name was left generic:\n%s", text)
	}
	for _, want := range []string{
		"type Persons []Person",
		"func (c Persons) Len() int",
		"func (c Persons) Append(more ...Person) Persons",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("the output does not hold %q:\n%s", want, text)
		}
	}
}

// Generated code lands in somebody else's package, where a helper called
// "counted" would collide with theirs — and the collision is a build failure in
// a file they did not write, about a name they never chose.
func TestWhatTheTemplateDeclaresTakesThePrefix(t *testing.T) {
	text := rendered(t, persons(t))

	for _, want := range []string{"type personsCounted struct", "func personsCount(seq iter.Seq[Person]) int"} {
		if !strings.Contains(text, want) {
			t.Errorf("the output does not hold %q:\n%s", want, text)
		}
	}
	// And the calls follow the declarations, or the output names something that
	// is not there.
	if !strings.Contains(text, "personsCount(c.All())") {
		t.Errorf("a call was left pointing at the unprefixed name:\n%s", text)
	}
	if strings.Contains(text, "counted{") {
		t.Errorf("a use of the helper kept its unprefixed name:\n%s", text)
	}
}

// A field reached through a value is not the package-level name it is spelled
// like, and renaming it would rewrite a use of the subject's own member.
func TestASelectedNameIsLeftAlone(t *testing.T) {
	text := rendered(t, persons(t))

	// The helper's fields keep their names; only the type they belong to is
	// renamed.
	for _, want := range []string{"tally.seen++", "first: true"} {
		if !strings.Contains(text, want) {
			t.Errorf("the output does not hold %q:\n%s", want, text)
		}
	}
}

// written renders a set of imports the way an import block would.
func written(imports []emit.Import) string {
	spelled := make([]string, len(imports))
	for i, one := range imports {
		spelled[i] = one.String()
	}
	return strings.Join(spelled, ",")
}

// The imports the template needed travel with it, since the file that is
// eventually written gathers them from everything that contributed.
func TestTheImportsTravelWithIt(t *testing.T) {
	out := persons(t)

	if want := `"iter","slices"`; written(out.Imports) != want {
		t.Errorf("the imports are %s, want %s", written(out.Imports), want)
	}
	// And no import declaration comes with them: the file writes one block.
	if text := rendered(t, out); strings.Contains(text, "import") {
		t.Errorf("an import declaration was carried through:\n%s", text)
	}
}

// The comments a template's author wrote are what a reader of the generated
// file reads, so they survive — but the package comment describes the template
// and would describe nothing in the file it lands in.
func TestTheCommentsSurviveExceptTheOneAboutTheTemplate(t *testing.T) {
	text := rendered(t, persons(t))

	for _, want := range []string{
		"// Len reports how many elements the collection holds.",
		"// Backward walks the collection from the end.",
		"// A method returning the container is where a rewrite most easily",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("the output does not hold %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "Package tmpl") {
		t.Errorf("the template's own package comment was carried through:\n%s", text)
	}
}

// Specialising the same template twice produces the same thing, or every run
// rewrites the file it wrote last time.
func TestSpecialisingTwiceProducesTheSameThing(t *testing.T) {
	first := rendered(t, persons(t))

	for range 3 {
		if again := rendered(t, persons(t)); again != first {
			t.Fatalf("one template specialised two ways:\n%s\n---\n%s", first, again)
		}
	}
}
