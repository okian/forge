// A package whose files are known only as compiled ones, or as neither, is
// still a package with a directory or without one.
func TestWhereAPackagesFilesAre(t *testing.T) {
	cases := map[string]*packages.Package{
		"the ordinary files": {GoFiles: []string{"/a/b/person.go"}},
		"the compiled ones":  {CompiledGoFiles: []string{"/a/b/person.go"}},
		"anything else":      {OtherFiles: []string{"/a/b/person.s"}},
	}

	for name, pkg := range cases {
		if got := directory(pkg); got != filepath.Clean("/a/b") {
			t.Errorf("%s put the package in %q", name, got)
		}
	}

	if got := directory(&packages.Package{}); got != "" {
		t.Errorf("a package with no files at all is in %q", got)
	}
}

// A package is written whole or not at all. Its files reach into each other —
// a declaration's own file calls helpers that live in the one the package
// shares — so writing the half that succeeded leaves a package holding an
// answer to a question the other half was going to ask.
func TestAPackageIsWrittenWholeOrNotAtAll(t *testing.T) {
	dir := t.TempDir()

	s := generating(t, dir, "Persons")
	broken := generating(t, dir, "Widgets")

	// One declaration that generates and one that cannot: an option naming a
	// field the subject does not have.
	broken.modelled[0].Declaration.Candidate.Directives = []discover.Directive{{
		Layer: "collection", Args: "sort=Nonesuch",
		Text: "//forge:collection sort=Nonesuch", ArgsOffset: 19,
		Pos: token.Position{Filename: filepath.Join(dir, "person.go"), Line: 7, Column: 1},
	}}
	s.modelled = append(s.modelled, broken.modelled...)

	_, said, err := running(t, s, "./...")
	if err == nil {
		t.Fatalf("a package with a declaration that cannot generate reported success\n%s", said)
	}

	held, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading the package back: %v", err)
	}
	for _, entry := range held {
		if strings.HasPrefix(entry.Name(), "zz_forge_") {
			t.Errorf("%s was written for a package that could not be generated whole", entry.Name())
		}
	}
}

// --dry-run answers the question it was asked. A run that reported nothing
// would be indistinguishable from one that found nothing to do, which is the
// one thing the flag exists to tell apart.
func TestWhatDryRunSaysWithoutBeingAskedTwice(t *testing.T) {
	dir := t.TempDir()

	out, errs := &bytes.Buffer{}, &bytes.Buffer{}
	env := &environment{stdout: out, stderr: errs, pipeline: over(generating(t, dir, "Persons"))}

	cmd, _ := lookup("generate")
	if err := cmd.run(env, cmd, []string{"--dry-run", "./..."}); err != nil {
		t.Fatalf("generating: %v", err)
	}

	// Without -v, which is the ordinary way somebody runs it.
	if !strings.Contains(errs.String(), "would write") {
		t.Errorf("a run held back said nothing:\n%s", errs.String())
	}
	if out.String() != "" {
		t.Errorf("it wrote to stdout, where a script reads:\n%s", out.String())
	}
}

// A file forge wrote for a declaration that is gone is what a rename leaves
// behind, and it is very often why the package no longer builds — so it is
// named rather than left to be inferred from a dozen errors about generated
// code, which is the last place an author who has just renamed a type looks.
func TestAFileLeftBehindByARename(t *testing.T) {
	dir := t.TempDir()

	if _, said, err := running(t, generating(t, dir, "Widgets"), "./..."); err != nil {
		t.Fatalf("the first run: %v\n%s", err, said)
	}

	// The same package with the declaration renamed, and no longer building —
	// which is what the file left behind did to it.
	_, said, err := running(t, broken(generating(t, dir, "Gadgets")), "./...")
	if err == nil {
		t.Fatalf("a package that does not build reported success\n%s", said)
	}

	if !strings.Contains(said, "FRG5003") || !strings.Contains(said, "zz_forge_widgets.go") {
		t.Errorf("the report does not name what was left behind:\n%s", said)
	}
	if !strings.Contains(said, "delete it") {
		t.Errorf("the report does not say what to do:\n%s", said)
	}

	// And the files the package still asks for are not named.
	for _, held := range []string{"zz_forge_gadgets.go", "zz_forge_shared.go"} {
		if strings.Contains(said, held+" does not belong") {
			t.Errorf("a file the package still asks for was named:\n%s", said)
		}
	}
}

// A leftover that breaks nothing is not worth stopping a run over. A package
// that builds is a package whose files, whatever else is true of them, are not
// stopping anybody — and a run refused because of one would refuse --dry-run
// and --diff too, which exist to answer a question without touching anything.
func TestALeftoverThatBreaksNothing(t *testing.T) {
	dir := t.TempDir()

	held := filepath.Join(dir, "zz_forge_ancient.go")
	if err := os.WriteFile(held, []byte("// Code generated by forge. DO NOT EDIT.\n\npackage model\n"), 0o600); err != nil {
		t.Fatalf("making the fixture: %v", err)
	}

	run := generating(t, dir, "Persons")

	// Listed in the package, as a load of a real directory would list it: the
	// file carries no build constraint, so nothing keeps it out of the build
	// and the type checker reads it along with everything else. A stand-in that
	// left it out would be standing in for a package that cannot exist.
	run.session.Packages[0].GoFiles = append(run.session.Packages[0].GoFiles, held)

	_, said, err := running(t, run, "./...")
	if err != nil {
		t.Fatalf("a package that builds was refused: %v\n%s", err, said)
	}
	if strings.Contains(said, "FRG5003") {
		t.Errorf("a leftover that breaks nothing stopped the run:\n%s", said)
	}
}

