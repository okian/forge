// generating builds a run holding one declaration in a package whose files live in
// dir, which is what generation writes beside.
//
// Built rather than loaded. What generation does with a resolved declaration is
// the thing under test, and a fixture module would put a go/packages session
// and a type-checker between this file and a written file.
func generating(t *testing.T, dir, declared string) *stack {
	t.Helper()

	source := filepath.Join(dir, "person.go")
	if err := os.WriteFile(source, []byte("package model\n"), 0o600); err != nil {
		t.Fatalf("making the fixture: %v", err)
	}

	pkg := &packages.Package{
		PkgPath: "example.com/model",
		Name:    "model",
		GoFiles: []string{source},
	}

	held := types.NewPackage("example.com/model", "model")
	obj := types.NewTypeName(token.NoPos, held, "Person", nil)

	subject := &model.Struct{
		Named:  types.NewNamed(obj, types.NewStruct(nil, nil), nil),
		Fields: []model.Field{{Name: "Name", Exported: true, Type: model.Classified{Type: types.Typ[types.String]}}},
	}

	candidate := discover.Candidate{
		Name: declared, Pkg: pkg, Form: model.FormInline,
		Pos: token.Position{Filename: source, Line: 8, Column: 6},
	}

	return &stack{
		session:    &load.Session{Fset: token.NewFileSet(), Packages: []*packages.Package{pkg}},
		candidates: []discover.Candidate{candidate},
		modelled: []request{{
			Declaration: resolve.Declaration{
				Candidate: candidate,
				Stack:     []model.LayerRef{{Origin: model.TypeRef{Pkg: model.MarkerPkg, Name: "Collection"}}},
			},
			Model: subject,
		}},
	}
}

// broken makes the package of a run one that does not build, which is the only
// state a file forge left behind is worth naming in.
func broken(s *stack) *stack {
	s.session.Packages[0].Errors = []packages.Error{{Msg: "undefined: Widgets"}}
	return s
}

// running drives the generate verb over a run, and returns what it said.
func running(t *testing.T, s *stack, args ...string) (string, string, error) {
	t.Helper()

	out, errs := &bytes.Buffer{}, &bytes.Buffer{}
	env := &environment{stdout: out, stderr: errs, pipeline: over(s), verbose: true}

	cmd, ok := lookup("generate")
	if !ok {
		t.Fatal("generate is not a command")
	}

	err := cmd.run(env, cmd, args)
	return out.String(), errs.String(), err
}

// A run writes what its declarations asked for, beside the source they were
// found in, and says what it did.
func TestARunWritesWhatWasAskedFor(t *testing.T) {
	dir := t.TempDir()
	s := generating(t, dir, "Persons")

	_, said, err := running(t, s, "./...")
	if err != nil {
		t.Fatalf("generating: %v\n%s", err, said)
	}

	for _, name := range []string{"zz_forge_persons.go", "zz_forge_shared.go"} {
		held, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatalf("%s was not written: %v", name, err)
		}
		if !bytes.Contains(held, []byte("Code generated by forge")) {
			t.Errorf("%s does not say it was generated", name)
		}
	}

	if !strings.Contains(said, "wrote 2 files") {
		t.Errorf("the run said\n%s", said)
	}
}

// The second run over unchanged inputs writes nothing, which is what keeps a
// generated file out of every diff and every rebuild that did not touch it.
func TestASecondRunTouchesNothing(t *testing.T) {
	dir := t.TempDir()

	if _, said, err := running(t, generating(t, dir, "Persons"), "./..."); err != nil {
		t.Fatalf("the first run: %v\n%s", err, said)
	}

	before := modified(t, filepath.Join(dir, "zz_forge_persons.go"))

	_, said, err := running(t, generating(t, dir, "Persons"), "./...")
	if err != nil {
		t.Fatalf("the second run: %v\n%s", err, said)
	}
	if !strings.Contains(said, "wrote 0 files") {
		t.Errorf("the second run said\n%s", said)
	}
	if after := modified(t, filepath.Join(dir, "zz_forge_persons.go")); !after.Equal(before) {
		t.Error("the second run rewrote a file holding what it would have written")
	}
}

// Neither flag that holds a run back writes anything, and one of them says what
// the difference would have been.
func TestTheFlagsThatHoldARunBack(t *testing.T) {
	for _, flag := range []string{"--dry-run", "--diff"} {
		t.Run(flag, func(t *testing.T) {
			dir := t.TempDir()

			shown, said, err := running(t, generating(t, dir, "Persons"), flag, "./...")
			if err != nil {
				t.Fatalf("generating: %v\n%s", err, said)
			}

			if _, err := os.Stat(filepath.Join(dir, "zz_forge_persons.go")); err == nil {
				t.Error("a run that was held back wrote a file")
			}
			if !strings.Contains(said, "would write 2 files") {
				t.Errorf("the run said\n%s", said)
			}

			if flag == "--diff" && !strings.Contains(shown, "+func (c Persons) Seq()") {
				t.Errorf("the difference does not show what would arrive:\n%s", shown)
			}
		})
	}
}

