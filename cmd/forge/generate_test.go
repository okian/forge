// A package with a declaration for another platform still gets told about a
// leftover in the half this run did read.
//
// Not reading all of a package costs the run its answer about the part it did
// not read, and nothing more. A file the run compiled is one it saw in full, so
// what the other configuration holds cannot change that this one accounts for
