// A leftover the load never saw is named whether or not the package builds.
//
// A declaration forge owns the type of generates into a file constrained
// against the tag forge itself loads under, so that file is outside every build
// this tool performs. It cannot break the package, so a report that waited for
// the package to break would wait for ever — and what waits for ever is a dead
// type sitting in the public API of the only build the author ships, after a
// rename that forge said nothing about.
func TestALeftoverTheLoadNeverSaw(t *testing.T) {
	dir := t.TempDir()

	held := filepath.Join(dir, "zz_forge_ancient.go")
	source := "// Code generated by forge. DO NOT EDIT.\n\n//go:build !forgespec\n\npackage model\n"
	if err := os.WriteFile(held, []byte(source), 0o600); err != nil {
		t.Fatalf("making the fixture: %v", err)
	}

	run := generating(t, dir, "Persons")

	// Listed among the files a constraint kept out, which is where a load of a
	// real directory puts it — and is the list a run has to read to tell a file
	// it excluded from one that is not there at all. A stand-in that left it out
	// would pass over a report that consulted the wrong list.
	run.session.Packages[0].IgnoredFiles = append(run.session.Packages[0].IgnoredFiles, held)

	_, said, err := running(t, run, "./...")

	if err == nil {
		t.Fatal("a file nothing in the package accounts for was not reported")
	}
	if !strings.Contains(said, "FRG5003") || !strings.Contains(said, "zz_forge_ancient.go") {
		t.Errorf("the report does not name the file:\n%s", said)
	}
}

// A run that read only part of a package says nothing about what it did not
// read.
//
// A spec file may carry more than the tag that makes it one — written under the
// tag and an operating system, it is a declaration only that system's run can
// see. Every other run finds the generated file belonging to no declaration it
// knows, and the two absences are the same absence.
//
// Saying so would be worse than saying nothing twice over: the author is told
// to delete a file the other platform needs, and the run is refused, taking
// every other package in it — and --dry-run and --diff with them, which exist
// to answer a question without touching anything. No invocation clears it,
// because forge does not take a tag to load under.
func TestAPackageThisRunOnlyPartlyRead(t *testing.T) {
	dir := t.TempDir()

	held := filepath.Join(dir, "zz_forge_ancient.go")
	source := "// Code generated by forge. DO NOT EDIT.\n\n//go:build !forgespec\n\npackage model\n"
	if err := os.WriteFile(held, []byte(source), 0o600); err != nil {
		t.Fatalf("making the fixture: %v", err)
	}

	// And the declaration it belongs to, in a file this configuration excluded.
	// Carrying no directive, because a directive is optional: what makes a
	// declaration is the marker in the type expression, so a rule that looked
	// for one would pass this file over and report the file written for it.
	spec := filepath.Join(dir, "spec.go")
	declaration := "//go:build forgespec && plan9\n\npackage model\n\ntype Ancients markers.Collection[Person]\n"
	if err := os.WriteFile(spec, []byte(declaration), 0o600); err != nil {
		t.Fatalf("making the fixture: %v", err)
	}

	run := generating(t, dir, "Persons")
	run.session.Packages[0].IgnoredFiles = append(run.session.Packages[0].IgnoredFiles, held, spec)

	_, said, err := running(t, run, "./...")
	if err != nil {
		t.Fatalf("a run that read part of a package was refused: %v\n%s", err, said)
	}
	if strings.Contains(said, "FRG5003") {
		t.Errorf("a file belonging to a declaration this run could not see was named:\n%s", said)
	}
}

